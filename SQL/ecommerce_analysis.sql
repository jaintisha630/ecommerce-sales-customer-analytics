-- Q32. What does customer retention look like?

WITH customer_orders AS (
    SELECT
        c.customer_id,
        c.customer_name,
        COUNT(DISTINCT o.order_id) AS valid_orders
    FROM customers c
    LEFT JOIN orders o
        ON c.customer_id = o.customer_id
        AND o.status <> 'Cancelled'
    GROUP BY c.customer_id, c.customer_name
),
customer_types AS (
    SELECT
        customer_id,
        customer_name,
        valid_orders,
        CASE
            WHEN valid_orders = 0 THEN 'No Valid Orders'
            WHEN valid_orders = 1 THEN 'One-Time'
            ELSE 'Repeat'
        END AS customer_type
    FROM customer_orders
)
SELECT
    customer_type,
    COUNT(*) AS total_customers,
    ROUND(
        COUNT(*) * 100.0 /
        SUM(COUNT(*)) OVER (),
        2
    ) AS percentage_of_customers
FROM customer_types
GROUP BY customer_type
ORDER BY total_customers DESC;


-- Q33. How does the product portfolio perform by revenue segment?

WITH product_performance AS (
    SELECT
        p.product_id,
        p.product_name,
        COALESCE(
            SUM(
                CASE
                    WHEN o.status <> 'Cancelled'
                    THEN p.price * oi.quantity
                    ELSE 0
                END
            ), 0
        ) AS product_revenue,
        COALESCE(
            SUM(
                CASE
                    WHEN o.status <> 'Cancelled'
                    THEN oi.quantity
                    ELSE 0
                END
            ), 0
        ) AS quantity_sold
    FROM products p
    LEFT JOIN order_items oi
        ON p.product_id = oi.product_id
    LEFT JOIN orders o
        ON oi.order_id = o.order_id
    GROUP BY p.product_id, p.product_name
),
product_segments AS (
    SELECT
        product_id,
        product_name,
        product_revenue,
        quantity_sold,
        CASE
            WHEN product_revenue = 0 THEN 'No Sales'
            WHEN product_revenue >= 5000 THEN 'High Revenue'
            WHEN product_revenue >= 2000 THEN 'Medium Revenue'
            ELSE 'Low Revenue'
        END AS revenue_segment
    FROM product_performance
)
SELECT
    revenue_segment,
    COUNT(*) AS total_products,
    SUM(quantity_sold) AS total_quantity_sold,
    SUM(product_revenue) AS segment_revenue
FROM product_segments
GROUP BY revenue_segment
ORDER BY segment_revenue DESC;


-- Q34. What are the company's headline business KPIs?

SELECT
    (SELECT COUNT(*) FROM customers) AS total_customers,

    (SELECT COUNT(*) FROM orders) AS total_orders,

    (
        SELECT COUNT(*)
        FROM orders
        WHERE status <> 'Cancelled'
    ) AS valid_orders,

    (
        SELECT COUNT(*)
        FROM orders
        WHERE status = 'Cancelled'
    ) AS cancelled_orders,

    (
        SELECT SUM(p.price * oi.quantity)
        FROM orders o
        JOIN order_items oi
            ON o.order_id = oi.order_id
        JOIN products p
            ON oi.product_id = p.product_id
        WHERE o.status <> 'Cancelled'
    ) AS total_revenue,

    ROUND(
        (
            SELECT SUM(p.price * oi.quantity)
            FROM orders o
            JOIN order_items oi
                ON o.order_id = oi.order_id
            JOIN products p
                ON oi.product_id = p.product_id
            WHERE o.status <> 'Cancelled'
        )
        /
        (
            SELECT COUNT(*)
            FROM orders
            WHERE status <> 'Cancelled'
        ),
        2
    ) AS average_order_value,

    (SELECT COUNT(*) FROM products) AS total_products,

    (
        SELECT SUM(oi.quantity)
        FROM order_items oi
        JOIN orders o
            ON oi.order_id = o.order_id
        WHERE o.status <> 'Cancelled'
    ) AS total_quantity_sold;


